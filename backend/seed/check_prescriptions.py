def parse_herbs(hstr):
    """解析 '人参9g、白术9g' → [(药名,剂量)]"""
    out = []
    for part in re.split(r'[、，,;；]', hstr):
        part = part.strip()
        if not part:
            continue
        m = re.match(r'^(.+?)([\d.]+(?:～|~|－|-)?[\d.]*)?(g|克|枚|片|钱|两|个|升|分|粒|枚|条|块|匙)$', part)
        if m:
            out.append((m.group(1).strip(), m.group(2) or '', m.group(3)))
        else:
            out.append((part, '', ''))
    return out

